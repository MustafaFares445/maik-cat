<?php

declare(strict_types=1);

namespace App\Console\Commands;

use App\Models\Item;
use App\Services\Media\ExistingItemImageRepairer;
use Illuminate\Console\Command;
use Illuminate\Support\Collection;
use Illuminate\Support\Str;
use InvalidArgumentException;
use RuntimeException;
use Spatie\MediaLibrary\MediaCollections\Models\Media;
use Throwable;

final class RepairItemImageLinksCommand extends Command
{
    private const array SOLVED_STATUSES = [
        'provenance_match',
        'visual_match_missing_provenance',
    ];

    private const array AUTO_REPAIR_STATUSES = [
        'confirmed_wrong_source',
        'missing_media_file',
    ];

    private const array BASE_TRUSTED_DONOR_STATUSES = [
        'provenance_match',
    ];

    private const array OUTPUT_HEADERS = [
        'status',
        'resolution',
        'reason',
        'item_id',
        'car_group',
        'serial_code',
        'normalized_serial',
        'item_source_url',
        'item_source_hash',
        'current_media_id',
        'current_media_file_name',
        'current_media_source_url',
        'current_media_source_hash',
        'expected_product_url',
        'expected_source_hash',
        'target_source_url',
        'target_source_hash',
        'match_method',
        'donor_item_id',
        'donor_media_id',
        'donor_media_file_name',
        'donor_media_source_url',
        'donor_media_source_hash',
        'donor_image_url',
        'result_media_id',
    ];

    protected $signature = 'media:repair-item-image-links
        {report : Path to image_link_audit.csv generated by media:audit-item-image-links}
        {--apply : Replace repairable images. Without this option the command is a dry run}
        {--output= : Output directory; defaults to a timestamped directory under storage/app/reports}
        {--code=* : Restrict target rows to one or more normalized serial codes}
        {--limit= : Maximum number of target issue rows to evaluate}
        {--include-visual-review-donors : Allow provenance_match_visual_review rows to act as donors}';

    protected $description = 'Repair item image identity issues by reusing trusted existing project media without downloading Ecotrade source images';

    public function handle(ExistingItemImageRepairer $repairer): int
    {
        try {
            $reportPath = $this->resolvePath((string) $this->argument('report'));
            $outputDirectory = $this->outputDirectory();
            $this->createOutputDirectory($outputDirectory);

            $rows = $this->readReport($reportPath);
            $trustedStatuses = $this->trustedDonorStatuses();
            $donorMedia = $this->loadTrustedDonorMedia($rows, $trustedStatuses);
            [$donorsByHash, $donorsByProductUrl] = $this->donorIndexes($rows, $donorMedia, $trustedStatuses);
            $targetRows = $this->targetRows($rows);
            $items = $this->loadTargetItems($targetRows);

            $plan = [];
            $unsolved = [];
            $alreadyCorrect = 0;
            $ignoredSolved = 0;

            foreach ($targetRows as $row) {
                $item = $items->get((string) ($row['item_id'] ?? ''));

                if (! $item instanceof Item) {
                    $unsolved[] = $this->outputRow($row, 'unsolved', 'target_item_missing', 'The target item no longer exists.');

                    continue;
                }

                if ($this->isAlreadyCorrect($item, $row)) {
                    $alreadyCorrect++;

                    continue;
                }

                $status = (string) ($row['status'] ?? '');

                if (in_array($status, self::SOLVED_STATUSES, true)) {
                    $ignoredSolved++;

                    continue;
                }

                if (! in_array($status, self::AUTO_REPAIR_STATUSES, true)) {
                    $unsolved[] = $this->outputRow(
                        $row,
                        'unsolved',
                        $this->manualReviewReason($status),
                        $this->manualReviewMessage($status),
                        item: $item,
                    );

                    continue;
                }

                $targetHash = $this->targetSourceHash($row, $item);
                $targetUrl = $this->targetProductUrl($row, $item);
                [$donor, $matchMethod] = $this->findDonor(
                    $item,
                    $targetHash,
                    $targetUrl,
                    $donorsByHash,
                    $donorsByProductUrl,
                );

                if (! $donor instanceof Media) {
                    $unsolved[] = $this->outputRow(
                        $row,
                        'unsolved',
                        ($targetHash === '' && $targetUrl === '')
                            ? 'no_authoritative_target_identity'
                            : 'no_trusted_existing_project_image',
                        ($targetHash === '' && $targetUrl === '')
                            ? 'No authoritative source hash or product URL is available for safe automatic replacement.'
                            : 'No trusted existing project image resolves to the expected product identity.',
                        item: $item,
                        targetHash: $targetHash,
                        targetUrl: $targetUrl,
                    );

                    continue;
                }

                $plan[] = $this->outputRow(
                    $row,
                    'repairable',
                    'trusted_existing_project_image',
                    'A trusted existing project image matches the expected product identity.',
                    item: $item,
                    donor: $donor,
                    targetHash: $targetHash,
                    targetUrl: $targetUrl,
                    matchMethod: $matchMethod,
                );
            }

            $this->writeCsv($outputDirectory.'/repair_plan.csv', $plan);

            $results = [];
            $failed = [];
            $repaired = 0;

            if ((bool) $this->option('apply')) {
                foreach ($plan as $planRow) {
                    try {
                        $item = $items->get((string) $planRow['item_id']);
                        $donorMediaId = (int) $planRow['donor_media_id'];
                        $donor = $donorMedia[$donorMediaId] ?? null;

                        if (! $item instanceof Item || ! $donor instanceof Media || ! is_file($donor->getPath())) {
                            throw new RuntimeException('Target item or donor media became unavailable before repair.');
                        }

                        $newMedia = $repairer->replaceWithExistingMedia($item, $donor);
                        $result = $planRow;
                        $result['resolution'] = 'repaired';
                        $result['reason'] = 'copied_trusted_existing_project_image';
                        $result['result_media_id'] = (string) $newMedia->getKey();
                        $results[] = $result;
                        $repaired++;
                    } catch (Throwable $exception) {
                        $failedRow = $planRow;
                        $failedRow['resolution'] = 'unsolved';
                        $failedRow['reason'] = 'repair_failed';
                        $failedRow['status'] = (string) $planRow['status'];
                        $failedRow['result_media_id'] = '';
                        $failedRow['match_method'] = (string) $planRow['match_method'];
                        $failedRow['donor_image_url'] = (string) $planRow['donor_image_url'];
                        $failedRow['reason'] = 'repair_failed: '.$exception->getMessage();
                        $failed[] = $failedRow;
                    }
                }
            }

            $unsolved = [...$unsolved, ...$failed];
            $this->writeCsv($outputDirectory.'/repair_results.csv', $results);
            $this->writeCsv($outputDirectory.'/unsolved_images.csv', $unsolved);
            $this->writeSummary($outputDirectory, [
                'report' => $reportPath,
                'apply' => (bool) $this->option('apply'),
                'rows_loaded' => count($rows),
                'target_rows' => count($targetRows),
                'trusted_donor_media' => count($donorMedia),
                'already_correct' => $alreadyCorrect,
                'ignored_solved' => $ignoredSolved,
                'repairable' => count($plan),
                'repaired' => $repaired,
                'failed' => count($failed),
                'unsolved' => count($unsolved),
            ]);

            $this->info((bool) $this->option('apply')
                ? 'Existing-project image repair completed.'
                : 'Existing-project image repair dry run completed without media changes.');
            $this->line('Rows loaded: '.count($rows));
            $this->line('Target issue rows: '.count($targetRows));
            $this->line('Trusted donor media: '.count($donorMedia));
            $this->line('Already correct: '.$alreadyCorrect);
            $this->line('Repairable from existing images: '.count($plan));
            $this->line('Images repaired: '.$repaired);
            $this->line('Unsolved images: '.count($unsolved));
            $this->line('Reports: '.$outputDirectory);

            if (! (bool) $this->option('apply') && $plan !== []) {
                $this->comment('Run the same command with --apply after reviewing repair_plan.csv.');
            }

            return self::SUCCESS;
        } catch (Throwable $exception) {
            $this->error('Existing-project image repair failed: '.$exception->getMessage());

            return self::FAILURE;
        }
    }

    /** @return list<array<string,string>> */
    private function readReport(string $path): array
    {
        if (! is_file($path)) {
            throw new RuntimeException('Audit CSV does not exist: '.$path);
        }

        $handle = fopen($path, 'rb');

        if ($handle === false) {
            throw new RuntimeException('Unable to open audit CSV: '.$path);
        }

        try {
            $headers = fgetcsv($handle);

            if (! is_array($headers) || $headers === []) {
                throw new RuntimeException('Audit CSV has no header row.');
            }

            $headers = array_map(static fn (mixed $value): string => (string) $value, $headers);
            $required = ['status', 'item_id', 'serial_code', 'item_source_url', 'item_source_hash', 'media_id', 'media_source_hash'];

            foreach ($required as $requiredHeader) {
                if (! in_array($requiredHeader, $headers, true)) {
                    throw new RuntimeException('Audit CSV is missing required column: '.$requiredHeader);
                }
            }

            $rows = [];

            while (($values = fgetcsv($handle)) !== false) {
                $row = [];

                foreach ($headers as $index => $header) {
                    $row[$header] = (string) ($values[$index] ?? '');
                }

                $rows[] = $row;
            }

            return $rows;
        } finally {
            fclose($handle);
        }
    }

    /** @param list<array<string,string>> $rows @param list<string> $trustedStatuses @return array<int,Media> */
    private function loadTrustedDonorMedia(array $rows, array $trustedStatuses): array
    {
        $mediaIds = collect($rows)
            ->filter(fn (array $row): bool => in_array((string) ($row['status'] ?? ''), $trustedStatuses, true))
            ->map(static fn (array $row): int => is_numeric($row['media_id'] ?? null) ? (int) $row['media_id'] : 0)
            ->filter()
            ->unique()
            ->values()
            ->all();

        if ($mediaIds === []) {
            return [];
        }

        return Media::query()
            ->with('model')
            ->whereIn('id', $mediaIds)
            ->where('model_type', Item::class)
            ->where('collection_name', 'images')
            ->get()
            ->filter(fn (Media $media): bool => $this->isSafeExistingDonor($media))
            ->keyBy(fn (Media $media): int => (int) $media->getKey())
            ->all();
    }

    private function isSafeExistingDonor(Media $media): bool
    {
        if (! is_file($media->getPath())) {
            return false;
        }

        $importMethod = Str::lower(trim((string) $media->getCustomProperty('import_method')));
        $fileName = Str::lower((string) $media->file_name);

        return $importMethod !== 'direct'
            && ! str_contains($fileName, 'ecotrade-direct');
    }

    /**
     * @param list<array<string,string>> $rows
     * @param array<int,Media> $donorMedia
     * @param list<string> $trustedStatuses
     * @return array{0:array<string,list<Media>>,1:array<string,list<Media>>}
     */
    private function donorIndexes(array $rows, array $donorMedia, array $trustedStatuses): array
    {
        $byHash = [];
        $byProductUrl = [];

        foreach ($rows as $row) {
            if (! in_array((string) ($row['status'] ?? ''), $trustedStatuses, true)) {
                continue;
            }

            $mediaId = is_numeric($row['media_id'] ?? null) ? (int) $row['media_id'] : 0;
            $media = $donorMedia[$mediaId] ?? null;

            if (! $media instanceof Media) {
                continue;
            }

            $sourceHash = trim((string) $media->getCustomProperty('source_hash'));

            if ($sourceHash !== '') {
                $byHash[$sourceHash][] = $media;
            }

            $item = $media->model;
            $productUrl = $item instanceof Item ? $this->normalizeUrl((string) ($item->source_url ?? '')) : '';

            if ($productUrl === '') {
                $productUrl = $this->normalizeUrl((string) ($row['item_source_url'] ?? ''));
            }

            if ($productUrl !== '') {
                $byProductUrl[$productUrl][] = $media;
            }
        }

        return [$byHash, $byProductUrl];
    }

    /** @param list<array<string,string>> $rows @return list<array<string,string>> */
    private function targetRows(array $rows): array
    {
        $codes = $this->normalizedCodes();
        $targets = array_values(array_filter($rows, function (array $row) use ($codes): bool {
            if ($codes === []) {
                return true;
            }

            return in_array(Item::normalizeSerialValue($row['normalized_serial'] ?: $row['serial_code']), $codes, true);
        }));
        $limit = $this->limit();

        return $limit === null ? $targets : array_slice($targets, 0, $limit);
    }

    /** @param list<array<string,string>> $rows */
    private function loadTargetItems(array $rows): Collection
    {
        $ids = collect($rows)
            ->pluck('item_id')
            ->filter()
            ->unique()
            ->values()
            ->all();

        if ($ids === []) {
            return collect();
        }

        return Item::query()
            ->with('media')
            ->whereIn('id', $ids)
            ->get()
            ->keyBy(fn (Item $item): string => (string) $item->getKey());
    }

    private function isAlreadyCorrect(Item $item, array $row): bool
    {
        $media = $item->getFirstMedia('images');

        if (! $media instanceof Media || ! is_file($media->getPath())) {
            return false;
        }

        $itemHash = trim((string) ($item->source_hash ?? ''));
        $mediaHash = trim((string) $media->getCustomProperty('source_hash'));

        if ($itemHash !== '' && $mediaHash !== '' && hash_equals($itemHash, $mediaHash)) {
            return true;
        }

        $expectedHash = trim((string) ($row['expected_source_hash'] ?? ''));

        return $expectedHash !== '' && $mediaHash !== '' && hash_equals($expectedHash, $mediaHash);
    }

    private function targetSourceHash(array $row, Item $item): string
    {
        $expectedHash = trim((string) ($row['expected_source_hash'] ?? ''));
        $referenceCount = is_numeric($row['reference_count'] ?? null) ? (int) $row['reference_count'] : 0;

        if ($expectedHash !== '' && $referenceCount === 1) {
            return $expectedHash;
        }

        $itemHash = trim((string) ($item->source_hash ?? ''));

        if ($itemHash !== '') {
            return $itemHash;
        }

        $reportedItemHash = trim((string) ($row['item_source_hash'] ?? ''));

        if ($reportedItemHash !== '') {
            return $reportedItemHash;
        }

        if ((string) ($row['status'] ?? '') === 'missing_media_file') {
            return trim((string) ($row['media_source_hash'] ?? ''));
        }

        return '';
    }

    private function targetProductUrl(array $row, Item $item): string
    {
        $expectedUrl = $this->normalizeUrl((string) ($row['expected_product_url'] ?? ''));
        $referenceCount = is_numeric($row['reference_count'] ?? null) ? (int) $row['reference_count'] : 0;

        if ($expectedUrl !== '' && $referenceCount === 1) {
            return $expectedUrl;
        }

        $itemUrl = $this->normalizeUrl((string) ($item->source_url ?? ''));

        return $itemUrl !== '' ? $itemUrl : $this->normalizeUrl((string) ($row['item_source_url'] ?? ''));
    }

    /** @param array<string,list<Media>> $donorsByHash @param array<string,list<Media>> $donorsByProductUrl @return array{0:Media|null,1:string} */
    private function findDonor(
        Item $target,
        string $targetHash,
        string $targetUrl,
        array $donorsByHash,
        array $donorsByProductUrl,
    ): array {
        if ($targetHash !== '') {
            $donor = $this->firstUsableDonor($target, $donorsByHash[$targetHash] ?? []);

            if ($donor instanceof Media) {
                return [$donor, 'source_hash'];
            }
        }

        if ($targetUrl !== '') {
            $donor = $this->firstUsableDonor($target, $donorsByProductUrl[$targetUrl] ?? []);

            if ($donor instanceof Media) {
                return [$donor, 'product_url'];
            }
        }

        return [null, ''];
    }

    /** @param list<Media> $donors */
    private function firstUsableDonor(Item $target, array $donors): ?Media
    {
        foreach ($donors as $donor) {
            if ((string) $donor->model_id === (string) $target->getKey() || ! $this->isSafeExistingDonor($donor)) {
                continue;
            }

            return $donor;
        }

        return null;
    }

    /** @return array<string,string> */
    private function outputRow(
        array $row,
        string $resolution,
        string $reason,
        string $message,
        ?Item $item = null,
        ?Media $donor = null,
        string $targetHash = '',
        string $targetUrl = '',
        string $matchMethod = '',
    ): array {
        $currentMedia = $item?->getFirstMedia('images');

        return [
            'status' => (string) ($row['status'] ?? ''),
            'resolution' => $resolution,
            'reason' => $reason.($message !== '' ? ': '.$message : ''),
            'item_id' => (string) ($row['item_id'] ?? $item?->getKey() ?? ''),
            'car_group' => (string) ($row['car_group'] ?? ''),
            'serial_code' => (string) ($row['serial_code'] ?? $item?->serial_code ?? ''),
            'normalized_serial' => (string) ($row['normalized_serial'] ?? ''),
            'item_source_url' => (string) ($item?->source_url ?? $row['item_source_url'] ?? ''),
            'item_source_hash' => (string) ($item?->source_hash ?? $row['item_source_hash'] ?? ''),
            'current_media_id' => (string) ($currentMedia?->getKey() ?? $row['media_id'] ?? ''),
            'current_media_file_name' => (string) ($currentMedia?->file_name ?? $row['media_file_name'] ?? ''),
            'current_media_source_url' => (string) ($currentMedia?->getCustomProperty('source_url') ?? $row['media_source_url'] ?? ''),
            'current_media_source_hash' => (string) ($currentMedia?->getCustomProperty('source_hash') ?? $row['media_source_hash'] ?? ''),
            'expected_product_url' => (string) ($row['expected_product_url'] ?? ''),
            'expected_source_hash' => (string) ($row['expected_source_hash'] ?? ''),
            'target_source_url' => $targetUrl,
            'target_source_hash' => $targetHash,
            'match_method' => $matchMethod,
            'donor_item_id' => (string) ($donor?->model_id ?? ''),
            'donor_media_id' => (string) ($donor?->getKey() ?? ''),
            'donor_media_file_name' => (string) ($donor?->file_name ?? ''),
            'donor_media_source_url' => (string) ($donor?->getCustomProperty('source_url') ?? ''),
            'donor_media_source_hash' => (string) ($donor?->getCustomProperty('source_hash') ?? ''),
            'donor_image_url' => (string) ($donor?->getFullUrl() ?? ''),
            'result_media_id' => '',
        ];
    }

    private function manualReviewReason(string $status): string
    {
        return match ($status) {
            'group_mapping_conflict' => 'group_mapping_conflict_requires_reference',
            'ambiguous_reference' => 'ambiguous_expected_product',
            'ambiguous_media_source' => 'ambiguous_media_provenance',
            'missing_reference' => 'no_expected_json_reference',
            'provenance_match_visual_review' => 'visual_review_required',
            'likely_visual_mismatch' => 'visual_mismatch_requires_manual_review',
            'missing_provenance' => 'missing_media_provenance',
            'unknown_media_source' => 'unknown_media_provenance',
            'missing_media' => 'missing_media_row',
            default => 'manual_review_required',
        };
    }

    private function manualReviewMessage(string $status): string
    {
        return match ($status) {
            'group_mapping_conflict' => 'The JSON product/group mapping is not authoritative enough for automatic replacement.',
            'ambiguous_reference' => 'More than one expected JSON product exists; no image is chosen automatically.',
            'ambiguous_media_source' => 'The current media provenance resolves to more than one product.',
            'missing_reference' => 'No expected JSON product exists for this item identity.',
            'provenance_match_visual_review' => 'The provenance is correct but the visual comparison still requires review.',
            'likely_visual_mismatch' => 'The image failed visual comparison and has no safe automatic donor rule.',
            'missing_provenance' => 'The current image has no source identity to verify automatically.',
            'unknown_media_source' => 'The current image source is not represented in the audit reference data.',
            'missing_media' => 'No current media row exists for the item.',
            default => 'This status is intentionally excluded from automatic image replacement.',
        };
    }

    /** @param list<array<string,string>> $rows */
    private function writeCsv(string $path, array $rows): void
    {
        $handle = fopen($path, 'wb');

        if ($handle === false) {
            throw new RuntimeException('Unable to create CSV: '.$path);
        }

        try {
            fputcsv($handle, self::OUTPUT_HEADERS);

            foreach ($rows as $row) {
                fputcsv($handle, array_map(
                    static fn (string $header): string => (string) ($row[$header] ?? ''),
                    self::OUTPUT_HEADERS,
                ));
            }
        } finally {
            fclose($handle);
        }
    }

    /** @param array<string,mixed> $summary */
    private function writeSummary(string $outputDirectory, array $summary): void
    {
        $written = file_put_contents(
            $outputDirectory.'/summary.json',
            json_encode($summary, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR),
        );

        if ($written === false) {
            throw new RuntimeException('Unable to write repair summary.');
        }
    }

    /** @return list<string> */
    private function trustedDonorStatuses(): array
    {
        $statuses = self::BASE_TRUSTED_DONOR_STATUSES;

        if ((bool) $this->option('include-visual-review-donors')) {
            $statuses[] = 'provenance_match_visual_review';
        }

        return $statuses;
    }

    /** @return list<string> */
    private function normalizedCodes(): array
    {
        return collect((array) $this->option('code'))
            ->map(static fn (mixed $code): string => Item::normalizeSerialValue($code))
            ->filter()
            ->unique()
            ->values()
            ->all();
    }

    private function limit(): ?int
    {
        $limit = $this->option('limit');

        if ($limit === null || $limit === '') {
            return null;
        }

        $validated = filter_var($limit, FILTER_VALIDATE_INT);

        if ($validated === false || $validated < 1) {
            throw new InvalidArgumentException('--limit must be a positive integer.');
        }

        return $validated;
    }

    private function outputDirectory(): string
    {
        $configured = trim((string) $this->option('output'));

        if ($configured === '') {
            return storage_path('app/reports/item-image-repair/'.now()->format('Ymd-His'));
        }

        return $this->resolvePath($configured);
    }

    private function createOutputDirectory(string $path): void
    {
        if (! is_dir($path) && ! mkdir($path, 0775, true) && ! is_dir($path)) {
            throw new RuntimeException('Unable to create output directory: '.$path);
        }
    }

    private function resolvePath(string $path): string
    {
        $path = trim($path);

        if ($path === '') {
            throw new InvalidArgumentException('A non-empty path is required.');
        }

        if (Str::startsWith($path, ['/', '\\']) || preg_match('/^[A-Za-z]:[\\\\\/]/', $path) === 1) {
            return rtrim($path, '\\/');
        }

        return rtrim(base_path($path), '\\/');
    }

    private function normalizeUrl(string $url): string
    {
        return Str::lower(trim($url));
    }
}
